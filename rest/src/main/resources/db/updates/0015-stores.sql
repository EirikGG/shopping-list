CREATE TABLE store (
    store_id        INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
    , session_id    UUID NOT NULL REFERENCES session(session_id)
    , person_id     INTEGER NOT NULL REFERENCES person (person_id)
    , name          VARCHAR(256) NOT NULL
    , created       TIMESTAMP NOT NULL
    , deleted       TIMESTAMP NULL
);

--changeset egg:2
CREATE UNIQUE INDEX ix_store_person_name_active_unique
    ON store (person_id, name)
    WHERE deleted IS NULL;


